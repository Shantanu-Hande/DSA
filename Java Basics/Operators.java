public class Operators{
    public static void main(String args[]){

        int a = 5;
        int b = 10;

        /*Arithmetic opertors
        System.out.println(a);
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(b%a);
        */

        /*Unary
        a = 10;
        b = ++a; // pre-increment
        System.out.println(a);
        System.out.println(b);

        a = 10;
        b = a++; // post-increment
        System.out.println(a);
        System.out.println(b);
        */

        /*Relational
        a = 10;
        b = 5;
        System.out.println(a==b);
        System.out.println(a!=b);
        System.out.println(a>b);
        System.out.println(a<b);
        System.out.println(a>=b);
        System.out.println(a<=b);
        */

        /*Logical
        System.out.println((3>2) && (2>1)); // Logical AND (Both should be true for true)
        System.out.println((4<0) || (5>9)); // Logical OR (Both should br false for false)
        System.out.println(!(5>0));//Logical Not (it convert true to false & false to true)
        */

       /*Assignment
       a = 2;
       a += 10;  // a = a + 10 
       System.out.println(a);

       b = 9;
       b -= 3; // b = b - 3
       System.out.println(b);

       a = 9;
       a *= 10; // a = a * 10
       System.out.println(a);

       b = 8;
       b /= 2; // b = b / 2
       System.out.println(b);
       */

      int x = 2, y =5;
      System.out.println(x*y/x);
    
    }
}